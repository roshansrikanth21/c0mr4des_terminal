"""The self-learning engine replayed the way it runs live: decide, see the outcome, relearn, repeat.

Every month from Jan 2023 the model is retrained on every trade that had closed by then (its own previous state),
then scores that month's new ideas. About 77,000 decisions, 47 relearning cycles.

The take-rule is then chosen mechanically on the 2023-2024 decisions only:
  score threshold in {0.05, 0.10, 0.15, 0.20, 0.25} x market groups in {all, only groups whose picks made money},
  best t-statistic with at least 300 picks.
It is frozen and judged once on 2025-2026. Pass mark as before: 300 trades, profit factor >= 1.15, t >= 2.

Writes data/learn_replay.pkl (every decision with its score and outcome) and research/LEARN_ONLINE_RESULTS.md.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from research import learn  # noqa: E402

NAMES = {0: "forex", 1: "gold", 2: "US indices", 3: "crypto"}
RISK = 0.5        # % of the account risked per taken trade, for the equity figures


def replay(t):
    cache = ROOT / "data" / "learn_replay.pkl"
    if cache.exists():
        return pd.read_pickle(cache)
    t = t.copy()
    t["pred"], t["cycle"] = np.nan, -1
    months = pd.date_range("2023-01-01", t["t_in"].max(), freq="MS")
    for k, start in enumerate(months):
        tr = t[t["t_out"] < start]
        te = t[(t["t_in"] >= start) & (t["t_in"] < start + pd.DateOffset(months=1))]
        if not len(te):
            continue
        m = learn.model().fit(tr[learn.FEATS], tr["R"].clip(-3, 5))
        t.loc[te.index, "pred"], t.loc[te.index, "cycle"] = m.predict(te[learn.FEATS]), k
        print(f"cycle {k + 1}/{len(months)} {start.date()} learned from {len(tr):,} closed trades, decided {len(te):,}", flush=True)
    t = t.dropna(subset=["pred"])
    t.to_pickle(cache)
    return t


def policy(d, thr, groups):
    return d[(d["pred"] > thr) & d["cls"].isin(groups)]


def gated(picks, months=12, need=30):
    """Each month keep only the picks in groups where the engine's own picks over the previous `months` made money."""
    keep, hist = [], []
    for m in pd.date_range("2024-01-01", picks["t_in"].max(), freq="MS"):
        past = picks[(picks["t_out"] < m) & (picks["t_out"] >= m - pd.DateOffset(months=months))]
        ok = [c for c, g in past.groupby("cls") if len(g) >= need and g["R"].mean() > 0]
        cur = picks[(picks["t_in"] >= m) & (picks["t_in"] < m + pd.DateOffset(months=1))]
        keep.append(cur[cur["cls"].isin(ok)])
        hist.append((str(m.date())[:7], ok))
    return pd.concat(keep), hist


def equity(p):
    daily = (p["R"] * RISK).groupby(p["t_out"].dt.normalize()).sum()
    eq = daily.cumsum()
    monthly = daily.groupby(daily.index.to_period("M")).sum()
    years = max((p["t_out"].max() - p["t_in"].min()).days / 365.25, 0.1)
    return {"per_year": daily.sum() / years, "dd": float((eq - eq.cummax()).min()), "months_up": int((monthly > 0).sum()),
            "months": len(monthly), "worst_month": float(monthly.min())}


def main():
    d = replay(learn.build_log())
    out = []
    w = out.append
    w("# Self-learning engine, replayed month by month\n")
    w(f"Generated by `learn_online.py`. **{len(d):,} decisions** over {d['cycle'].nunique()} learn-decide cycles, Jan 2023 to "
      f"{d['t_in'].max().date()}. Each month's model had seen only trades that closed before that month.\n")
    val, judge = d[d["t_in"] < "2025-01-01"], d[d["t_in"] >= "2025-01-01"]

    w("## 1. Choosing the take-rule on 2023-2024 only\n")
    w("| Score above | Market groups | Picks 2023-24 | Avg R | PF | t-stat |")
    w("|---|---|---|---|---|---|")
    best = None
    for thr in (0.05, 0.10, 0.15, 0.20, 0.25):
        good = [c for c in NAMES if learn.stats(policy(val, thr, [c])["R"])["avg"] > 0 and len(policy(val, thr, [c])) >= 30]
        for label, groups in (("all", list(NAMES)), ("profitable ones: " + ", ".join(NAMES[c] for c in good), good)):
            s = learn.stats(policy(val, thr, groups)["R"])
            w(f"| +{thr:.2f}R | {label} | {s['n']} | {s['avg']:+.3f} | {s['pf']:.2f} | {s['t']:.1f} |")
            if s["n"] >= 300 and (best is None or s["t"] > best[0]):
                best = (s["t"], thr, groups, label)
    _, thr, groups, label = best
    w(f"\nChosen (best t-statistic with 300+ picks): **score above +{thr:.2f}R, {label}**. Frozen.\n")

    w("## 2. The frozen rule on 2025-2026, which played no part in choosing it\n")
    w("| | Trades | Win % | Avg R | PF | t-stat | Total R |")
    w("|---|---|---|---|---|---|---|")
    pj = policy(judge, thr, groups)
    for lab, g in (("Every idea, no model", judge), ("Same market groups, no model", judge[judge["cls"].isin(groups)]),
                   ("Engine's picks", pj), ("Engine's picks, 2025", pj[pj["t_in"] < "2026-01-01"]),
                   ("Engine's picks, 2026", pj[pj["t_in"] >= "2026-01-01"])):
        s = learn.stats(g["R"])
        w(f"| {lab} | {s['n']} | {100 * (g['R'] > 0).mean():.0f} | {s['avg']:+.3f} | {s['pf']:.2f} | {s['t']:.1f} | {s['tot']:+.0f} |")
    s = learn.stats(pj["R"])
    ok = s["n"] >= 300 and s["pf"] >= 1.15 and s["t"] >= 2
    w(f"\nPass mark (300 trades, PF 1.15, t 2): **{'PASSED' if ok else 'NOT PASSED'}** ({s['n']} trades, PF {s['pf']:.2f}, t {s['t']:.1f}).\n")

    w(f"## 3. What that would have meant in money, risking {RISK}% of the account per trade\n")
    w("| Period | Return a year | Worst drawdown | Months up | Worst month |")
    w("|---|---|---|---|---|")
    for lab, g in (("2023-24 (rule was chosen here)", policy(val, thr, groups)), ("2025-26 (unseen)", pj)):
        if len(g):
            e = equity(g)
            w(f"| {lab} | {e['per_year']:+.1f}% | {e['dd']:.1f}% | {e['months_up']} of {e['months']} | {e['worst_month']:+.1f}% |")

    w("\n## 4. The engine's 2025-26 picks by rule and market group\n")
    w("| Rule | Market group | Picks | Avg R | PF |")
    w("|---|---|---|---|---|")
    for (s_, c_), g in sorted(pj.groupby(["strat", "cls"]), key=lambda kv: -len(kv[1]))[:12]:
        s = learn.stats(g["R"])
        w(f"| {s_} | {NAMES[c_]} | {s['n']} | {s['avg']:+.3f} | {s['pf']:.2f} |")

    w("\n## 5. Did it get better as it learned?\n")
    w("| Quarter | Decisions | Picks | Picks avg R | Skipped avg R | Gap |")
    w("|---|---|---|---|---|---|")
    for per, g in d.groupby(d["t_in"].dt.to_period("Q")):
        p, sk = policy(g, thr, groups), g[~g.index.isin(policy(g, thr, groups).index)]
        if len(p) > 20:
            w(f"| {per} | {len(g)} | {len(p)} | {p['R'].mean():+.3f} | {sk['R'].mean():+.3f} | {p['R'].mean() - sk['R'].mean():+.3f} |")
    w("\n## 6. The self-adjusting version: trade a market group only while the engine's own picks there are making money\n")
    w("One design, no tuning: each month, a market group is allowed only if the engine's own picks in it (score above +0.05R) over the "
      "previous 12 months number at least 30 and averaged above zero. 2023 is the warm-up year.\n")
    w("| | Trades | Win % | Avg R | PF | t-stat | Total R |")
    w("|---|---|---|---|---|---|---|")
    picks = d[d["pred"] > 0.05]
    kept, allowed_log = gated(picks)
    for lab, g in (("2024", kept[kept["t_in"] < "2025-01-01"]), ("2025", kept[(kept["t_in"] >= "2025-01-01") & (kept["t_in"] < "2026-01-01")]),
                   ("2026", kept[kept["t_in"] >= "2026-01-01"]), ("2025-26 (the judge)", kept[kept["t_in"] >= "2025-01-01"]),
                   ("2024-26", kept), ("Same picks without the gate, 2024-26", picks[picks["t_in"] >= "2024-01-01"])):
        s = learn.stats(g["R"])
        w(f"| {lab} | {s['n']} | {100 * (g['R'] > 0).mean():.0f} | {s['avg']:+.3f} | {s['pf']:.2f} | {s['t']:.1f} | {s['tot']:+.0f} |")
    s = learn.stats(kept[kept["t_in"] >= "2025-01-01"]["R"])
    ok = s["n"] >= 300 and s["pf"] >= 1.15 and s["t"] >= 2
    e = equity(kept)
    w(f"\nPass mark (300 trades, PF 1.15, t 2 on 2025-26): **{'PASSED' if ok else 'NOT PASSED'}** ({s['n']} trades, PF {s['pf']:.2f}, "
      f"t {s['t']:.1f}). At {RISK}% risk a trade over 2024-26: {e['per_year']:+.1f}% a year, worst drawdown {e['dd']:.1f}%, "
      f"{e['months_up']} of {e['months']} months up, worst month {e['worst_month']:+.1f}%.")
    w("\nGroups allowed, every fourth month: " + "; ".join(f"{m}: {', '.join(NAMES[c] for c in ok_) or 'none'}" for m, ok_ in allowed_log[::4]) + ".")
    w("\nThis is the third take-rule tried on this log (fixed threshold, threshold chosen on 2023-24, then this gate). "
      "It was run once with these settings, but a pass on a third attempt is weaker evidence than a pass on the first.")
    seed = picks[["cls", "t_out", "R"]].assign(t_out=picks["t_out"].astype(str))
    (ROOT / "data" / "learner_seed.json").write_text(seed.to_json(orient="records"), encoding="utf-8")
    (ROOT / "research" / "LEARN_ONLINE_RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
