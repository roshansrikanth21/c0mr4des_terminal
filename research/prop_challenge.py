"""Score the prop_zoo strategies, then play the survivors through a prop-firm challenge.

Selection rule, fixed before any result: a strategy (all instruments pooled, equal risk per trade) is picked on
2021-2024 if it has at least 100 trades, profit factor >= 1.10 and at least 3 of 4 years positive. It is then
judged once on 2025-2026.

Challenge model (the common two-step form): phase 1 needs +10%, phase 2 +5%; the account dies on a day that loses
5% of the starting balance or when the total loss reaches 10%. Funded: same limits, 80% of profit paid out every
14 days, for the first 180 days. Risk per trade is a fixed share of the starting balance. Losses are counted when a
trade closes, so open losses inside a day are not seen (flattering). Attempts are simulated by drawing whole weeks
of the book's real daily results at random.

Writes research/PROP_RESULTS.md.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SPLIT = pd.Timestamp("2025-01-01")
FEE_PCT = 0.6            # challenge fee as % of the account: about $540 on a $100k two-step account
RISKS = (0.5, 1.0, 2.0)


def stats(t):
    r = t["R"].values
    if not len(r):
        return {"n": 0, "win": 0, "avg": 0, "pf": 0, "tot": 0}
    w, l = r[r > 0].sum(), -r[r <= 0].sum()
    return {"n": len(r), "win": 100 * (r > 0).mean(), "avg": r.mean(), "pf": w / l if l else 0, "tot": r.sum()}


def daily_pnl(t, risk, start, end):
    s = (t["R"] * risk).groupby(t["t_out"].dt.normalize()).sum()
    return s.reindex(pd.bdate_range(start, end), fill_value=0.0)


def run_phase(p, k, target):
    """Return (outcome, next index). outcome: 'pass', 'fail', 'end' (path ran out)."""
    eq, n = 0.0, len(p)
    while k < n:
        d = p[k]
        eq += d
        k += 1
        if d <= -5 or eq <= -10:
            return "fail", k
        if eq >= target:
            return "pass", k
    return "end", k


def funded(p, k, days=128):          # 128 business days ~ 180 calendar days
    paid, eq, n, k0 = 0.0, 0.0, len(p), k
    while k < n and k - k0 < days:
        d = p[k]
        eq += d
        k += 1
        if d <= -5 or eq <= -10:
            break
        if (k - k0) % 10 == 0 and eq > 0:
            paid += 0.8 * eq
            eq = 0.0
    return paid


def one(p):
    """One challenge from the first day of path p: (passed phase 1, passed both, paid %, business days to pass)."""
    o1, k = run_phase(p, 0, 10)
    if o1 != "pass":
        return 0, 0, 0.0, np.nan
    o2, k2 = run_phase(p, k, 5)
    if o2 != "pass":
        return 1, 0, 0.0, np.nan
    return 1, 1, funded(p, k2), k2


def play(day_pnl, rng, paths=4000, years=3):
    """Monte Carlo: build paths by drawing whole weeks of the book's real daily P&L at random, with replacement."""
    weeks = np.array([day_pnl[i:i + 5] for i in range(0, len(day_pnl) - 4, 5)])
    n = 52 * years + 26
    a = np.array([one(weeks[rng.integers(0, len(weeks), n)].ravel()) for _ in range(paths)], dtype=float)
    passed = a[:, 1] == 1
    return {"p1": 100 * a[:, 0].mean(), "pass": 100 * passed.mean(), "pass1y": 100 * (a[:, 3] <= 260).mean(),
            "days": float(np.nanmedian(a[:, 3])) * 7 / 5 if passed.any() else float("nan"),
            "paid_any": 100 * (a[:, 2] > 0).mean(), "paid": a[:, 2].mean()}


def row(w, name, label, risk, r):
    w(f"| {name} | {label} | {risk}% | {r['p1']:.0f} | {r['pass']:.0f} | {r['pass1y']:.0f} | {r['days']:.0f} | {r['paid_any']:.0f} | "
      f"{r['paid']:.2f} | {r['paid'] - FEE_PCT:+.2f} | ${1000 * (r['paid'] - FEE_PCT):+,.0f} |")


def main():
    t = pd.read_pickle(ROOT / "data" / "prop_trades.pkl")
    out = []
    w = out.append
    w("# Prop-firm route: forex, gold and US indices\n")
    w(f"Generated by `prop_challenge.py`. {len(t):,} trades, {t['strat'].nunique()} strategies, instruments: "
      f"{', '.join(sorted(t['sym'].unique()))}. Hourly bars {t['t_in'].min().date()} to {t['t_out'].max().date()}, costs included. "
      "R = multiples of the amount risked on a trade.\n")

    w("## 1. Strategies, all instruments pooled\n")
    w("| Strategy | Trades | Win % | Avg R | PF build 2021-24 | Years + (build) | PF judge 2025-26 | Total R judge | Picked on build |")
    w("|---|---|---|---|---|---|---|---|---|")
    picked = []
    for name, g in sorted(t.groupby("strat")):
        b, j = g[g["t_in"] < SPLIT], g[g["t_in"] >= SPLIT]
        sb, sj, sa = stats(b), stats(j), stats(g)
        yrs = int((b.groupby(b["t_in"].dt.year)["R"].sum() > 0).sum())
        ok = sb["n"] >= 100 and sb["pf"] >= 1.10 and yrs >= 3
        if ok:
            picked.append(name)
        w(f"| {name} | {sa['n']} | {sa['win']:.0f} | {sa['avg']:+.3f} | {sb['pf']:.2f} | {yrs}/4 | {sj['pf']:.2f} | {sj['tot']:+.0f} | {'yes' if ok else ''} |")
    held = [n for n in picked if stats(t[(t["strat"] == n) & (t["t_in"] >= SPLIT)])["pf"] > 1.0]
    w(f"\nPicked on the build years: **{len(picked)} of {t['strat'].nunique()}**. Still profitable on the unseen years: **{len(held)}**.")
    for n in picked:
        for label, g in (("2021-24", t[(t["strat"] == n) & (t["t_in"] < SPLIT)]["R"]), ("2025-26", t[(t["strat"] == n) & (t["t_in"] >= SPLIT)]["R"])):
            w(f"\n{n}, {label}: {len(g)} trades, average {g.mean():+.3f}R, total {g.sum():+.0f}R, t-statistic "
              f"{g.mean() / (g.std() / np.sqrt(len(g))):.2f} (2 is the usual bar for 'not luck').")

    w("\n## 2. Strategy x instrument, how many hold up\n")
    cells = both = build_ok = 0
    best = []
    for (name, sym), g in t.groupby(["strat", "sym"]):
        b, j = g[g["t_in"] < SPLIT], g[g["t_in"] >= SPLIT]
        if len(b) < 30 or len(j) < 10:
            continue
        cells += 1
        sb, sj = stats(b), stats(j)
        if sb["pf"] >= 1.10:
            build_ok += 1
            both += sj["pf"] > 1.0
            best.append((sb["pf"], name, sym, sb["n"], sj["pf"], sj["n"], sj["tot"]))
    w(f"{cells} strategy-instrument pairs with enough trades. {build_ok} had build PF >= 1.10; of those, {both} stayed above 1.0 on 2025-26 "
      f"({100 * both / max(build_ok, 1):.0f}%).\n")
    w("Top ten by build profit factor:\n")
    w("| Strategy | Instrument | Build PF (trades) | Judge PF (trades) | Judge total R |")
    w("|---|---|---|---|---|")
    for pf, name, sym, n, jpf, jn, jtot in sorted(best, reverse=True)[:10]:
        w(f"| {name} | {sym} | {pf:.2f} ({n}) | {jpf:.2f} ({jn}) | {jtot:+.0f} |")

    w("\n## 3. The challenge, simulated\n")
    w(f"Each row is 4,000 simulated attempts built from random weeks of the book's real daily results (three and a half years allowed, since "
      f"the big firms no longer set a deadline). Fee assumed {FEE_PCT}% of the account (about $540 on $100k). 'Paid' is the average payout "
      "over the first 180 funded days as % of the account, per challenge bought, failures included. Net = paid minus one fee.\n")
    w("| Book | Results drawn from | Risk/trade | Pass phase 1 % | Pass both % | Pass both within a year % | Median days to pass | "
      "Got a payout % | Paid % | Net % | Net on $100k |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    rng = np.random.default_rng(7)
    books = {n: t[t["strat"] == n] for n in picked}
    typical = min(t["strat"].unique(), key=lambda n: abs(stats(t[t["strat"] == n])["avg"] + 0.05))
    books[f"For contrast, a typical losing one: {typical}"] = t[t["strat"] == typical]
    end = str(t["t_out"].max().date())
    for name, g in books.items():
        for label, a_, b_ in (("2021-24", "2021-01-01", "2024-12-31"), ("2025-26", "2025-01-01", end)):
            gg = g[(g["t_out"] >= a_) & (g["t_out"] <= b_ + " 23:59")]
            for risk in RISKS:
                row(w, name, label, risk, play(daily_pnl(gg, risk, a_, b_).values, rng))
    for label, drift in (("Coin flip, one trade a day, no costs", 0.0), ("Coin flip, one trade a day, with costs (-0.05R)", -0.05)):
        for risk in RISKS:
            row(w, label, "random", risk, play((rng.choice([1.0, -1.0], 500_000) + drift) * risk, rng))
    (ROOT / "research" / "PROP_RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
